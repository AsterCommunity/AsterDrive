/// Exactly one connector credential channel supplied by an API caller.
///
/// The tagged representation makes static credentials and authorization
/// application credentials structurally mutually exclusive. Each connector
/// deserializes `values` into the typed credential struct generated by its
/// schema declaration.
#[derive(Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "mode", content = "values", rename_all = "snake_case")]
#[cfg_attr(all(debug_assertions, feature = "openapi"), derive(ToSchema))]
pub enum StorageConnectorCredentialInput {
    /// No credential is supplied; only connectors whose descriptor declares
    /// no credential mode accept this variant.
    #[default]
    None,
    /// Values for a connector-held static secret, shaped by the connector's
    /// credential schema.
    Static(serde_json::Value),
    /// Values for the OAuth application a delegated connector authorizes
    /// through its own authorization workflow.
    AuthorizationApplication(serde_json::Value),
}

impl std::fmt::Debug for StorageConnectorCredentialInput {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(match self {
            Self::None => "None",
            Self::Static(_) => "Static(<redacted>)",
            Self::AuthorizationApplication(_) => "AuthorizationApplication(<redacted>)",
        })
    }
}

